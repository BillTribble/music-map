#!/usr/bin/env python3
"""Measure ITU-R BS.1770-4 / EBU R128 Loudness Across All Music Map Tracks & Sync data.js.

Computes integrated loudness (`lufs`), true peak (`true_peak_db`), loudness range (`lra_lu`),
reference gain offset (`gain_db` relative to `TARGET_LUFS = -16.5`), and linear `gain_trim`
for every track in `js/data.js` (`tracks`, `eras`, `phases`).

Persists canonical measurements in `scripts/track_loudness.json` and fixes any non-linear
`gain_trim` entries in `scripts/latest_masters_2026.json` so rebuilds via `build_data.py`
or `build_discogs_map.py` (and `--apply-only` post-rebase syncs) are 100% deterministic.
"""

from __future__ import annotations

import argparse
import concurrent.futures
import json
import math
import os
import re
import subprocess
import tempfile
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DATA_JS = ROOT / "js" / "data.js"
DEFAULT_LOUDNESS_JSON = ROOT / "scripts" / "track_loudness.json"
DEFAULT_MASTERS_2026_JSON = ROOT / "scripts" / "latest_masters_2026.json"
DEFAULT_CACHE_DIR = Path(
    os.environ.get("BEATGRID_AUDIO_CACHE")
    or (Path(os.environ.get("SWARM_TMP_ROOT") or tempfile.gettempdir()) / "drop_audio_cache")
)

TARGET_LUFS = -16.5
MIN_GAIN_DB = -18.0
MAX_BOOST_DB = 12.0
LIMITER_CEILING_DBTP = -1.0
MAX_LIMITER_GR_DB = 6.0

_RE_INT_LUFS = re.compile(r"Integrated loudness:\s+I:\s+(-?\d+(?:\.\d+)?)\s+LUFS", re.MULTILINE)
_RE_LRA = re.compile(r"Loudness range:\s+LRA:\s+(-?\d+(?:\.\d+)?)\s+LU", re.MULTILINE)
_RE_TP = re.compile(r"True peak:\s+Peak:\s+(-?\d+(?:\.\d+)?)\s+dBFS", re.MULTILINE)


def clamp(val: float, lo: float, hi: float) -> float:
    return max(lo, min(hi, val))


def compute_loudness_gains(
    lufs: float,
    true_peak_db: float | None = None,
    target_lufs: float = TARGET_LUFS,
) -> tuple[float, float]:
    """Return `(gain_db, gain_trim)` for a track relative to `target_lufs`."""
    raw_db = clamp(target_lufs - float(lufs), MIN_GAIN_DB, MAX_BOOST_DB)
    if raw_db > 0.0 and true_peak_db is not None and math.isfinite(true_peak_db):
        max_peak_safe_db = (LIMITER_CEILING_DBTP - float(true_peak_db)) + MAX_LIMITER_GR_DB
        raw_db = min(raw_db, max(-6.0, max_peak_safe_db))
    gain_db = round(raw_db, 2)
    gain_trim = round(math.pow(10.0, gain_db / 20.0), 4)
    return gain_db, gain_trim


def load_data_js(data_js_path: Path) -> dict:
    raw = data_js_path.read_text(encoding="utf-8")
    marker = "window.CORPUS_DATA = "
    idx = raw.index(marker)
    body = raw[idx + len(marker) :].rstrip()
    if body.endswith(";"):
        body = body[:-1]
    return json.loads(body)


def save_data_js(data_js_path: Path, payload: dict) -> None:
    serialized = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    out = f"// Auto-generated by scripts/build_data.py\nwindow.CORPUS_DATA = {serialized};\n"
    data_js_path.write_text(out, encoding="utf-8")


def ensure_local_audio(track: dict, cache_dir: Path) -> Path:
    tid = str(track["id"])
    for ext in (".m4a", ".webm", ".mp3", ".wav", ".flac"):
        cand = cache_dir / f"{tid}{ext}"
        if cand.exists() and cand.stat().st_size > 8000:
            return cand

    cache_dir.mkdir(parents=True, exist_ok=True)
    urls = [
        u
        for u in (
            track.get("stream_url"),
            track.get("mp3_320_url"),
            track.get("mp3_url"),
            track.get("preview_url"),
            track.get("file"),
        )
        if isinstance(u, str) and u.startswith("http")
    ]
    last_err = None
    for url in urls:
        low = url.lower()
        ext = ".m4a" if ".m4a" in low else (".webm" if ".webm" in low else ".mp3")
        dest = cache_dir / f"{tid}{ext}"
        for attempt in range(3):
            try:
                req = urllib.request.Request(url, headers={"User-Agent": "music-map-lufs/1.0"})
                with urllib.request.urlopen(req, timeout=60) as resp:
                    blob = resp.read()
                if len(blob) < 4000:
                    raise RuntimeError(f"Tiny audio payload ({len(blob)}B)")
                tmp = cache_dir / f"{tid}{ext}.part"
                tmp.write_bytes(blob)
                os.replace(tmp, dest)
                return dest
            except Exception as exc:
                last_err = str(exc)
                time.sleep(0.4 * (attempt + 1))
    raise RuntimeError(f"Could not fetch audio for {tid}: {last_err}")


def measure_ebur128(audio_path: Path, fallback_rms_db: float | None = None) -> dict:
    ffmpeg_bin = "/usr/bin/ffmpeg" if os.path.exists("/usr/bin/ffmpeg") else "ffmpeg"
    proc = subprocess.run(
        [
            ffmpeg_bin,
            "-threads",
            "1",
            "-nostats",
            "-hide_banner",
            "-i",
            str(audio_path),
            "-af",
            "ebur128=peak=true:framelog=quiet",
            "-f",
            "null",
            "-",
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    log = (proc.stderr or "") + "\n" + (proc.stdout or "")
    m_i = _RE_INT_LUFS.findall(log)
    m_lra = _RE_LRA.findall(log)
    m_tp = _RE_TP.findall(log)

    lufs: float | None = float(m_i[-1]) if m_i else None
    if lufs is None or not math.isfinite(lufs) or lufs <= -65.0:
        rms_fb = float(fallback_rms_db) if fallback_rms_db is not None else -18.0
        lufs = clamp(rms_fb - 0.7, -45.0, -3.0)

    true_peak_db = float(m_tp[-1]) if m_tp else -1.0
    if not math.isfinite(true_peak_db) or true_peak_db <= -90.0:
        true_peak_db = round(lufs + 12.0, 1)

    lra_lu = float(m_lra[-1]) if m_lra else 6.0
    if not math.isfinite(lra_lu) or lra_lu < 0.0:
        lra_lu = 6.0

    lufs_r = round(lufs, 1)
    tp_r = round(true_peak_db, 1)
    lra_r = round(lra_lu, 1)
    gain_db, gain_trim = compute_loudness_gains(lufs_r, tp_r, TARGET_LUFS)
    return {
        "lufs": lufs_r,
        "true_peak_db": tp_r,
        "lra_lu": lra_r,
        "gain_db": gain_db,
        "gain_trim": gain_trim,
    }


def _measure_worker(args_tuple: tuple[dict, str]) -> tuple[str, dict]:
    track, cache_dir_str = args_tuple
    tid = str(track["id"])
    fb_rms = track.get("rms_db")
    try:
        audio_path = ensure_local_audio(track, Path(cache_dir_str))
        res = measure_ebur128(audio_path, fb_rms)
        res["source"] = "ebur128"
        return tid, res
    except Exception:
        rms_fb = float(fb_rms) if fb_rms is not None else -16.5
        lufs_r = round(clamp(rms_fb - 0.7, -45.0, -3.0), 1)
        tp_r = round(min(0.0, lufs_r + 12.5), 1)
        gain_db, gain_trim = compute_loudness_gains(lufs_r, tp_r, TARGET_LUFS)
        return tid, {
            "lufs": lufs_r,
            "true_peak_db": tp_r,
            "lra_lu": 6.0,
            "gain_db": gain_db,
            "gain_trim": gain_trim,
            "source": "rms_fallback",
        }


def apply_entry_to_track_obj(track: dict, entry: dict) -> None:
    lufs_r = round(float(entry["lufs"]), 1)
    tp_r = round(float(entry.get("true_peak_db", -1.0)), 1)
    gain_db, gain_trim = compute_loudness_gains(lufs_r, tp_r, TARGET_LUFS)
    track["lufs"] = lufs_r
    track["true_peak_db"] = tp_r
    track["gain_db"] = gain_db
    track["gain_trim"] = gain_trim


def sync_masters_2026_bundle(masters_path: Path, tracks_map: dict[str, dict]) -> int:
    if not masters_path.exists():
        return 0
    bundle = json.loads(masters_path.read_text(encoding="utf-8"))
    updated = 0
    for item in bundle.get("tracks", []):
        tid = str(item.get("id") or "")
        if tid in tracks_map:
            apply_entry_to_track_obj(item, tracks_map[tid])
            updated += 1
    if updated > 0:
        masters_path.write_text(json.dumps(bundle, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return updated


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data-js", type=Path, default=DEFAULT_DATA_JS)
    ap.add_argument("--loudness-json", type=Path, default=DEFAULT_LOUDNESS_JSON)
    ap.add_argument("--cache-dir", type=Path, default=DEFAULT_CACHE_DIR)
    ap.add_argument("--workers", type=int, default=min(32, max(4, os.cpu_count() or 8)))
    ap.add_argument("--apply-only", action="store_true", help="Apply cached track_loudness.json onto js/data.js without re-measuring cached tracks")
    ap.add_argument("--recompute", action="store_true", help="Force re-measuring all tracks even if cached")
    args = ap.parse_args()

    t0 = time.time()
    payload = load_data_js(args.data_js)
    tracks = payload.get("tracks", [])

    existing_map: dict[str, dict] = {}
    if args.loudness_json.exists() and not args.recompute:
        loaded = json.loads(args.loudness_json.read_text(encoding="utf-8"))
        existing_map = dict(loaded.get("tracks") or {})

    # Recompute derived gain_db/gain_trim on cached entries in case TARGET_LUFS changed
    for tid, ent in existing_map.items():
        gdb, gtrim = compute_loudness_gains(ent["lufs"], ent.get("true_peak_db"), TARGET_LUFS)
        ent["gain_db"] = gdb
        ent["gain_trim"] = gtrim

    missing_tracks = [t for t in tracks if str(t["id"]) not in existing_map]
    if missing_tracks:
        print(f"Measuring EBU R128 loudness on {len(missing_tracks)}/{len(tracks)} tracks ({args.workers} workers)...")
        work_items = [(t, str(args.cache_dir)) for t in missing_tracks]
        with concurrent.futures.ProcessPoolExecutor(max_workers=args.workers) as pool:
            for tid, res in pool.map(_measure_worker, work_items):
                existing_map[tid] = res

    # Persist canonical sorted track_loudness.json
    ordered_tracks = {tid: existing_map[tid] for tid in sorted(existing_map.keys())}
    lufs_vals = sorted(float(existing_map[str(t["id"])]["lufs"]) for t in tracks)
    n = len(lufs_vals)
    summary = {
        "target_lufs": TARGET_LUFS,
        "min_gain_db": MIN_GAIN_DB,
        "max_boost_db": MAX_BOOST_DB,
        "limiter_ceiling_dbtp": LIMITER_CEILING_DBTP,
        "total_active_tracks": n,
        "lufs_min": lufs_vals[0] if n else None,
        "lufs_p10": lufs_vals[int(n * 0.10)] if n else None,
        "lufs_median": lufs_vals[n // 2] if n else None,
        "lufs_p90": lufs_vals[int(n * 0.90)] if n else None,
        "lufs_max": lufs_vals[-1] if n else None,
    }
    out_json = {"summary": summary, "tracks": ordered_tracks}
    args.loudness_json.write_text(json.dumps(out_json, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    # Apply across payload["tracks"], payload["eras"][*]["tracks"], and payload["phases"][*]["tracks"]
    applied_main = 0
    for tr in tracks:
        tid = str(tr.get("id") or "")
        if tid in existing_map:
            apply_entry_to_track_obj(tr, existing_map[tid])
            applied_main += 1

    for section_key in ("eras", "phases"):
        for group in payload.get(section_key, []):
            for tr in group.get("tracks", []):
                tid = str(tr.get("id") or "")
                if tid in existing_map:
                    apply_entry_to_track_obj(tr, existing_map[tid])

    if isinstance(payload.get("meta"), dict):
        payload["meta"]["loudness_target_lufs"] = TARGET_LUFS

    save_data_js(args.data_js, payload)
    synced_2026 = sync_masters_2026_bundle(DEFAULT_MASTERS_2026_JSON, existing_map)
    dt = time.time() - t0
    print(
        f"Applied EBU R128 loudness ({TARGET_LUFS} LUFS ref) to {applied_main}/{len(tracks)} tracks "
        f"(+{synced_2026} in latest_masters_2026.json) in {dt:.2f}s | "
        f"LUFS min={summary['lufs_min']} p10={summary['lufs_p10']} med={summary['lufs_median']} "
        f"p90={summary['lufs_p90']} max={summary['lufs_max']}"
    )


if __name__ == "__main__":
    main()
